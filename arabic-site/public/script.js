// ===== تنضيف الكلمة =====
function clean(text) {
  text = text.replace(/[\u0617-\u061A\u064B-\u0652]/g, ""); // حذف التشكيل
  text = text.replace(/[أإآ]/g, "ا");
  text = text.replace(/ى/g, "ي");
  return text.replace(/[.,،؟!؛:]/g, "").trim();
}

function inList(list, w) {
  return list.indexOf(w) !== -1;
}

// هل الكلمة معرفة؟ (بترجع الإجابة أو "" لو نكرة)
function definiteType(w) {
  if (inList(PRONOUNS, w)) return "معرفة (ضمير منفصل)";
  if (inList(DEMONSTRATIVES, w)) return "معرفة (اسم إشارة)";
  if (inList(RELATIVES, w)) return "معرفة (اسم موصول)";
  if (inList(PROPER, w)) return "معرفة (اسم علم)";
  if (w.indexOf("ال") === 0 && w.length > 3) return "معرفة (معرف بـ ال)";
  for (var i = 0; i < ATTACHED.length; i++) {
    var p = ATTACHED[i];
    if (w.length - p.length >= 3 && w.slice(-p.length) === p) {
      return "معرفة (مضاف إلى الضمير " + p + ")";
    }
  }
  return "";
}

// ===== فحص كلمة واحدة =====
function checkOne(w) {
  // 1) حروف
  if (PARTICLES[w]) return PARTICLES[w];

  // 2) معارف أساسية
  var d = definiteType(w);
  if (d !== "" && w.indexOf("ال") !== 0) return d;

  // 3) أفعال معروفة
  if (KNOWN_VERBS[w]) return KNOWN_VERBS[w];

  // 4) المعرف بال اسم
  if (d !== "") return d;

  // 5) تخمين الفعل من الشكل
  if (w.length >= 4 && "يتنا".indexOf(w.charAt(0)) !== -1 && w.charAt(0) !== "ا") {
    return "فعل مضارع (تخمين من أول الكلمة)";
  }
  if (w.length >= 4 && w.slice(-2) === "وا") return "فعل ماض (تخمين: واو الجماعة)";
  if (w.length >= 4 && w.slice(-2) === "ت" + "م") return "فعل ماض (تخمين: تم)";
  if (w.length >= 4 && w.slice(-1) === "ت") return "فعل ماض (تخمين: تاء الفاعل) أو اسم مؤنث";

  // 6) غير كده نكرة
  return "اسم نكرة";
}

// ===== الزرار =====
function check() {
  var text = clean(document.getElementById("word").value);
  var words = text.split(/\s+/);
  var out = document.getElementById("result");

  if (text === "") {
    out.textContent = "اكتب كلمة الأول";
    return;
  }

  if (words.length > 1) {
    out.textContent = "اكتب كلمة واحدة بس مش جملة";
    return;
  }

  out.textContent = "النتيجة: " + checkOne(words[0]);
}
